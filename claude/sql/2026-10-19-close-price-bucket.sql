--
-- ЩО ЦЕ ЛАГОДИТЬ. Станом на сьогодні файл price.xlsx (10,6 МБ, увесь прайс із цінами)
-- віддається БУДЬ-КОМУ за прямим посиланням, без входу в застосунок. Перевірено запитом
-- без авторизації: HTTP 206. Жодні гейти доступу в інтерфейсі цього не змінюють.
--
-- ⚠️ ПЕРЕД ВИКОНАННЯМ переконатись, що:
--   1. Застосунок на пристроях — версії 2026-10-19.21 або новішої (у ній аварійне
--      завантаження прайсу йде через сесію, а не по публічній адресі).
--   2. У логах Storage за добу немає звернень до /object/public/price/price.xlsx
--      від чужих IP (перевірка «Публікація прайсу» в самодіагностиці каже про це прямо).
--   3. Опублікована версія прайсу має фото серій (media) — інакше застосунок полізе
--      по Excel за фотографіями. Зараз: версія №2 від 18.10, media на 8 аркушів.
--
-- ВІДКАТ (якщо щось пішло не так — одна команда, діє негайно):
--   update storage.buckets set public = true where id = 'price';
--   create policy "public read price files" on storage.objects
--     for select to public using (bucket_id = 'price');

begin;

-- 1. Прибираємо дозвіл «читати всім».
drop policy if exists "public read price files" on storage.objects;

-- 2. Читати файл може лише той, кому застосунок і так показує ціни.
--    ⚠️ Правило ДОСЛІВНО повторює profileAllowsPrices() у js/07-access-info.js і
--    правило доступу до залишків у get_stock(). Міняєш тут — міняй і там.
--    Заблокованим (status = 'blocked') — ні. Тим, хто «на розгляді» (pending), — так:
--    це свідоме рішення власника, доступ відкривається одразу після реєстрації.
create policy "price file for users with price access"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'price'
    and exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and coalesce(p.status, 'pending') <> 'blocked'
    )
  );

-- 3. Сам бакет більше не публічний: без цього кроку політика нічого не вирішує,
--    бо публічний бакет віддає файли в обхід RLS.
update storage.buckets set public = false where id = 'price';

commit;

-- ПІСЛЯ ВИКОНАННЯ перевірити обидва боки:
--   а) без авторизації має бути 400/404, а не 200:
--      curl -s -o /dev/null -w "%{http_code}\n" \
--        "https://pwyeifgjfyymhhvzigcg.supabase.co/storage/v1/object/public/price/price.xlsx"
--   б) у застосунку під адміном відкрити Кабінет → «Самодіагностика» → «Перевірити зараз»:
--      рядок «Старий price.xlsx закритий» має бути в переліку перевіреного, а не в проблемах.
--
-- УВАГА, що цей скрипт НЕ чіпає: бакет price-media лишається публічним. Там лежать фото
