-- Спроба «за компанію» відкликати EXECUTE на current_role()/current_region()
-- у ролі anon ЛАМАЄ ГОСТЬОВИЙ ДОСТУП:
--
--   політики таблиці profiles кличуть ці функції, тому гостьовий SELECT по profiles
--   починає падати з «permission denied for function current_region» замість того,
--   щоб чесно повернути 0 рядків.
--
-- Тобто замість тиші гість отримує помилку — а це вхід/реєстрація.
-- Перевірено прямим запитом від ролі anon: до відкликання 0 рядків, після —
-- виняток, після повернення права знову 0 рядків.
--
-- Безпеки відкликання все одно не давало: у гостя немає auth.uid(), обидві функції
-- віддають йому null.
--
-- Якщо колись знову захочеться «почистити» ці дві функції — спершу перечитати цей
-- абзац. Правильний стан:
grant execute on function public."current_role"() to anon, authenticated;
grant execute on function public.current_region() to anon, authenticated;

