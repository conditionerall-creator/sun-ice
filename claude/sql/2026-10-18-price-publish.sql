-- =====================================================================
-- ⚠️ Станом на 2026-10-18 застосовано ЛИШЕ до стенду `sun-ice-stend`
--    (ref mhngmnxugguqfoxtwjej). До боевого — тільки за окремим дозволом
--    власника і лише після етапу C (звірка на справжньому прайсі).
--
-- Що це. Кабінет супер-адміна розбирає Excel на пристрої й кладе сюди ГОТОВІ дані.
-- Дилери читають їх функцією get_price() і Excel більше не качають.
--
-- Правила, закладені в схему:
--   1. price_versions / price_state / price_audit НЕ мають жодної RLS-політики і
--      в них відкликані всі права для anon/authenticated — з браузера туди не
--      заглянути й не записати. Увесь доступ лише через функції нижче.
--   2. Правило «кому видно ціни» в get_price() дослівно повторює profileAllowsPrices()
--      з js/07-access-info.js і те саме місце в get_stock(). Це ТРЕТЄ місце з тим
--      самим правилом — МІНЯТИ ВСІ ТРИ РАЗОМ.
--   3. Публікація — compare-and-swap: публікатор називає версію, яку вважає поточною.
--      Розійшлось — відмова, а не тихий перезапис чужої роботи.
--   4. ВІДМОВА НЕ КИДАЄ ВИНЯТОК. Перша версія кидала — і виняток відкочував запис
--      в аудит, зроблений тією ж транзакцією, тож журнал відмов лишався порожнім
--      (знайдено тестом 2026-10-18, до того це виглядало як робочий код).
--      Тепер відмова — звичайна відповідь {ok:false,error:...}, і аудит виживає.
--   5. price_publish приймає p_legacy_version і оновлює price_meta.version.
--      Поки частина телефонів ще читає price.xlsx, без цього вони лишилися б зі
--      старим прайсом, і ніхто б цього не помітив.
--
-- Рішення про зберігання (питання 1 плану, закрите 2026-10-18): готові дані лежать
-- рядком у Postgres (jsonb), а не файлом у Storage. Причина: йде через наявні правила
-- доступу, без підписаних посилань і без другої системи зберігання. Якщо розмір стане
-- проблемою — переїзд у Storage не зачіпає клієнтський код, бо той ходить через RPC.
-- =====================================================================

-- ---------- Версії прайсу ----------
create table if not exists public.price_versions (
  id              bigint generated by default as identity primary key,
  status          text not null default 'draft' check (status in ('draft','published','archived')),
  data            jsonb not null,                       -- розібраний прайс (sheetsData)
  stats           jsonb not null default '{}'::jsonb,   -- скільки позицій у кожному розділі
  diff            jsonb not null default '{}'::jsonb,   -- що змінилось проти попередньої
  parser_version  integer,                              -- PARSER_VERSION, яким розбирали
  app_build       text,                                 -- APP_BUILD пристрою-публікатора
  source_name     text,                                 -- ім'я вихідного файлу
  source_sha256   text,                                 -- хеш вихідного Excel
  legacy_version  integer,                              -- яку price_meta.version виставили
  idempotency_key text unique,                          -- повтор після обриву не дає дубль
  created_by      uuid references auth.users(id),
  created_at      timestamptz not null default now(),
  published_by    uuid references auth.users(id),
  published_at    timestamptz,
  prev_version_id bigint references public.price_versions(id)
);
alter table public.price_versions enable row level security;
revoke all on public.price_versions from anon, authenticated;

-- ---------- Покажчик активної версії ----------
-- price_meta НЕ замінюємо: там версія старого xlsx, нею живуть ще не оновлені телефони.
create table if not exists public.price_state (
  id                 integer primary key default 1 check (id = 1),
  current_version_id bigint references public.price_versions(id),
  updated_at         timestamptz not null default now()
);
insert into public.price_state (id, current_version_id) values (1, null) on conflict (id) do nothing;
alter table public.price_state enable row level security;
revoke all on public.price_state from anon, authenticated;

-- ---------- Аудит ----------
create table if not exists public.price_audit (
  id           bigint generated by default as identity primary key,
  action       text not null check (action in ('draft','publish','rollback','refused')),
  from_version bigint,
  to_version   bigint,
  ok           boolean not null,
  reason       text,
  actor        uuid,
  actor_role   text,
  created_at   timestamptz not null default now()
);
alter table public.price_audit enable row level security;
revoke all on public.price_audit from anon, authenticated;

-- ---------- Хто має право керувати прайсом ----------
-- Рішення власника 2026-10-18: ЛИШЕ super_admin. Регіональні адміни — ні.
-- Роль читається з БД за auth.uid(), ніколи з тіла запиту.
create or replace function public.price_is_manager()
returns boolean language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from public.profiles
                  where id = auth.uid() and role = 'super_admin' and status = 'approved');
$$;

-- ---------- Створення чернетки ----------
create or replace function public.price_create_draft(
  p_data jsonb, p_stats jsonb default '{}'::jsonb, p_diff jsonb default '{}'::jsonb,
  p_parser_version integer default null, p_app_build text default null,
  p_source_name text default null, p_source_sha256 text default null,
  p_idempotency_key text default null
) returns jsonb language plpgsql security definer set search_path to 'public' as $$
declare v_id bigint; v_prev bigint;
begin
  if not public.price_is_manager() then
    insert into public.price_audit (action, ok, reason, actor, actor_role)
    values ('refused', false, 'create_draft: not a super_admin', auth.uid(), public."current_role"());
    return jsonb_build_object('ok', false, 'error', 'only_super_admin');
  end if;

  if p_data is null or jsonb_typeof(p_data) <> 'object' then
    insert into public.price_audit (action, ok, reason, actor, actor_role)
    values ('refused', false, 'create_draft: data is not an object', auth.uid(), public."current_role"());
    return jsonb_build_object('ok', false, 'error', 'bad_data');
  end if;

  -- Повтор тієї ж операції (обрив мережі) віддає вже створену чернетку.
  if p_idempotency_key is not null then
    select id into v_id from public.price_versions where idempotency_key = p_idempotency_key;
    if v_id is not null then
      return jsonb_build_object('ok', true, 'id', v_id, 'repeated', true);
    end if;
  end if;

  select current_version_id into v_prev from public.price_state where id = 1;

  insert into public.price_versions (status, data, stats, diff, parser_version, app_build,
         source_name, source_sha256, idempotency_key, created_by, prev_version_id)
  values ('draft', p_data, coalesce(p_stats,'{}'::jsonb), coalesce(p_diff,'{}'::jsonb),
          p_parser_version, p_app_build, p_source_name, p_source_sha256,
          p_idempotency_key, auth.uid(), v_prev)
  returning id into v_id;

  insert into public.price_audit (action, from_version, to_version, ok, actor, actor_role)
  values ('draft', v_prev, v_id, true, auth.uid(), public."current_role"());

  return jsonb_build_object('ok', true, 'id', v_id);
end; $$;

-- ---------- Публікація (compare-and-swap) ----------
create or replace function public.price_publish(
  p_version_id bigint, p_expected_current bigint default null, p_legacy_version integer default null
) returns jsonb language plpgsql security definer set search_path to 'public' as $$
declare v_cur bigint; v_stat text;
begin
  if not public.price_is_manager() then
    insert into public.price_audit (action, to_version, ok, reason, actor, actor_role)
    values ('refused', p_version_id, false, 'publish: not a super_admin', auth.uid(), public."current_role"());
    return jsonb_build_object('ok', false, 'error', 'only_super_admin');
  end if;

  select current_version_id into v_cur from public.price_state where id = 1 for update;

  if coalesce(p_expected_current, -1) is distinct from coalesce(v_cur, -1) then
    insert into public.price_audit (action, from_version, to_version, ok, reason, actor, actor_role)
    values ('refused', v_cur, p_version_id, false,
            'publish: expected current ' || coalesce(p_expected_current::text,'null') ||
            ', actual ' || coalesce(v_cur::text,'null'), auth.uid(), public."current_role"());
    return jsonb_build_object('ok', false, 'error', 'stale_current',
                              'actual_current_version_id', v_cur);
  end if;

  select status into v_stat from public.price_versions where id = p_version_id;
  if v_stat is null then
    insert into public.price_audit (action, from_version, to_version, ok, reason, actor, actor_role)
    values ('refused', v_cur, p_version_id, false, 'publish: no such version', auth.uid(), public."current_role"());
    return jsonb_build_object('ok', false, 'error', 'no_such_version');
  end if;

  update public.price_versions set status = 'archived' where status = 'published' and id <> p_version_id;
  update public.price_versions
     set status='published', published_by=auth.uid(), published_at=now(),
         legacy_version = coalesce(p_legacy_version, legacy_version)
   where id = p_version_id;
  update public.price_state set current_version_id = p_version_id, updated_at = now() where id = 1;

  -- Старі клієнти досі читають price.xlsx і звіряються з price_meta.version.
  if p_legacy_version is not null then
    update public.price_meta set version = p_legacy_version, updated_at = now() where id = 1;
  end if;

  insert into public.price_audit (action, from_version, to_version, ok, actor, actor_role)
  values ('publish', v_cur, p_version_id, true, auth.uid(), public."current_role"());

  return jsonb_build_object('ok', true, 'current_version_id', p_version_id,
                            'previous_version_id', v_cur);
end; $$;

-- ---------- Відкат ----------
-- Не видалення й не «мінус крок», а НОВА подія перемикання на стару версію.
-- Історія лишається цілою.
create or replace function public.price_rollback(
  p_version_id bigint, p_expected_current bigint default null, p_reason text default null
) returns jsonb language plpgsql security definer set search_path to 'public' as $$
declare v_cur bigint; v_leg integer;
begin
  if not public.price_is_manager() then
    insert into public.price_audit (action, to_version, ok, reason, actor, actor_role)
    values ('refused', p_version_id, false, 'rollback: not a super_admin', auth.uid(), public."current_role"());
    return jsonb_build_object('ok', false, 'error', 'only_super_admin');
  end if;

  select current_version_id into v_cur from public.price_state where id = 1 for update;

  if coalesce(p_expected_current, -1) is distinct from coalesce(v_cur, -1) then
    insert into public.price_audit (action, from_version, to_version, ok, reason, actor, actor_role)
    values ('refused', v_cur, p_version_id, false, 'rollback: stale expected_current',
            auth.uid(), public."current_role"());
    return jsonb_build_object('ok', false, 'error', 'stale_current',
                              'actual_current_version_id', v_cur);
  end if;

  if not exists (select 1 from public.price_versions where id = p_version_id) then
    insert into public.price_audit (action, from_version, to_version, ok, reason, actor, actor_role)
    values ('refused', v_cur, p_version_id, false, 'rollback: no such version',
            auth.uid(), public."current_role"());
    return jsonb_build_object('ok', false, 'error', 'no_such_version');
  end if;

  update public.price_versions set status = 'archived' where status = 'published';
  update public.price_versions set status='published', published_by=auth.uid(), published_at=now()
   where id = p_version_id returning legacy_version into v_leg;
  update public.price_state set current_version_id = p_version_id, updated_at = now() where id = 1;

  -- Старим клієнтам теж треба повернути стару версію, інакше вони лишаться на новій.
  if v_leg is not null then
    update public.price_meta set version = v_leg, updated_at = now() where id = 1;
  end if;

  insert into public.price_audit (action, from_version, to_version, ok, reason, actor, actor_role)
  values ('rollback', v_cur, p_version_id, true, p_reason, auth.uid(), public."current_role"());

  return jsonb_build_object('ok', true, 'current_version_id', p_version_id,
                            'previous_version_id', v_cur);
end; $$;

-- ---------- Видача цін дилерам ----------
-- ⚠️ Правило доступу — дослівна копія profileAllowsPrices() (js/07-access-info.js)
--    і того ж місця в get_stock(). ТРИ місця, міняти разом.
create or replace function public.get_price()
returns jsonb language plpgsql stable security definer set search_path to 'public' as $$
declare v_uid uuid := auth.uid(); v_status text; v_rereg timestamptz;
        v_allowed boolean; v_id bigint; v_row public.price_versions%rowtype;
begin
  if v_uid is null then return null; end if;
  select status, reregistered_at into v_status, v_rereg from public.profiles where id = v_uid;
  v_allowed := v_status is not null
               and v_status not in ('blocked','rejected')
               and not (v_status = 'pending' and v_rereg is not null);
  if not v_allowed then return null; end if;
  select current_version_id into v_id from public.price_state where id = 1;
  if v_id is null then return null; end if;
  select * into v_row from public.price_versions where id = v_id;
  if v_row.id is null then return null; end if;
  return jsonb_build_object('version_id', v_row.id, 'published_at', v_row.published_at,
                            'stats', v_row.stats, 'data', v_row.data);
end; $$;

-- ---------- Легка перевірка «чи є новіша версія» ----------
-- Без тіла прайсу: телефон питає це часто, качати 1,7 МБ щоразу безглуздо.
create or replace function public.get_price_version()
returns jsonb language plpgsql stable security definer set search_path to 'public' as $$
declare v_uid uuid := auth.uid(); v_status text; v_rereg timestamptz;
        v_allowed boolean; v_id bigint; v_at timestamptz;
begin
  if v_uid is null then return null; end if;
  select status, reregistered_at into v_status, v_rereg from public.profiles where id = v_uid;
  v_allowed := v_status is not null
               and v_status not in ('blocked','rejected')
               and not (v_status = 'pending' and v_rereg is not null);
  if not v_allowed then return null; end if;
  select ps.current_version_id, pv.published_at into v_id, v_at
    from public.price_state ps left join public.price_versions pv on pv.id = ps.current_version_id
   where ps.id = 1;
  if v_id is null then return null; end if;
  return jsonb_build_object('version_id', v_id, 'published_at', v_at);
end; $$;

-- ---------- Історія версій (лише super_admin) ----------
create or replace function public.price_list_versions(p_limit integer default 20)
returns jsonb language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not public.price_is_manager() then return null; end if;
  return (
    select coalesce(jsonb_agg(x order by (x->>'id')::bigint desc), '[]'::jsonb)
    from (
      select jsonb_build_object('id', v.id, 'status', v.status, 'created_at', v.created_at,
               'published_at', v.published_at, 'source_name', v.source_name,
               'stats', v.stats, 'diff', v.diff, 'legacy_version', v.legacy_version,
               'author', coalesce(p.full_name,'')) as x
        from public.price_versions v
        left join public.profiles p on p.id = coalesce(v.published_by, v.created_by)
       order by v.id desc limit greatest(1, least(coalesce(p_limit,20), 100))
    ) t
  );
end; $$;

